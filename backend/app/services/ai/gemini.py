from typing import Tuple, Dict, Any
from .base import BaseAIProvider

class GoogleGeminiProvider(BaseAIProvider):
    def __init__(self, name: str = "Google Gemini", api_key: str = "", api_endpoint: str = "", model: str = "gemini-2.5-flash"):
        endpoint = api_endpoint.strip() if api_endpoint else "https://generativelanguage.googleapis.com"
        super().__init__(name, api_key, endpoint, model or "gemini-2.5-flash")

    def test_connection(self) -> Tuple[bool, str]:
        if not self.api_key:
            return False, "Gemini API key is required"
        try:
            url = f"{self.api_endpoint.rstrip('/')}/v1beta/models/{self.model}?key={self.api_key}"
            res = self._http_request(url, method="GET", timeout=15)
            display_name = res.get("displayName", self.model)
            return True, f"Successfully connected to Google Gemini ({display_name})"
        except Exception as e:
            return False, str(e)

    def generate_text(self, prompt: str, system_prompt: str = "", temperature: float = 0.7) -> str:
        if not self.api_key:
            raise ValueError("Google Gemini API key is missing. Configure it in AI Settings.")

        url = f"{self.api_endpoint.rstrip('/')}/v1beta/models/{self.model}:generateContent?key={self.api_key}"
        
        payload: Dict[str, Any] = {
            "contents": [
                {
                    "parts": [{"text": prompt}]
                }
            ],
            "generationConfig": {
                "temperature": temperature,
                "maxOutputTokens": 2048,
            }
        }
        
        if system_prompt:
            payload["systemInstruction"] = {
                "parts": [{"text": system_prompt}]
            }

        res = self._http_request(url, method="POST", data=payload, timeout=60)
        try:
            candidates = res.get("candidates", [])
            if not candidates:
                raise ValueError("No response generated by Gemini model.")
            parts = candidates[0].get("content", {}).get("parts", [])
            text = "".join([part.get("text", "") for part in parts])
            return text.strip()
        except KeyError as e:
            raise RuntimeError(f"Unexpected response structure from Gemini: {res}")
